// ─── Index ───────────────────────────────────────────────────────────────────

interface IndexedDistrict {
  name: string;
  province: string;
  record: DistrictRecord;
}

/** ชื่อเขต/อำเภอ (normalize แล้ว) → ข้อมูลเขต */
const districtIndex = new Map<string, IndexedDistrict>();
/** ชื่อแขวง/ตำบล (normalize แล้ว) → เขตที่แขวงนั้นอยู่ (แขวงชื่อซ้ำข้ามเขตได้) */
const khwaengIndex = new Map<string, IndexedDistrict[]>();

/** ตัดคำนำหน้าและช่องว่างออก เพื่อให้ "เขตบางแค" / "บางแค " จับคู่กันได้ */
export function normalizeAreaName(raw: string): string {
  return raw
    .trim()
    .replace(/^(เขต|แขวง|อำเภอ|ตำบล|จังหวัด|อ\.|ต\.|จ\.)\s*/, '')
    .replace(/\s+/g, '')
    .toLowerCase();
}

for (const group of PROVINCES) {
  for (const [name, record] of Object.entries(group.districts)) {
    const entry: IndexedDistrict = { name, province: group.province, record };
    districtIndex.set(normalizeAreaName(name), entry);
    for (const khwaeng of record.khwaeng) {
      const key = normalizeAreaName(khwaeng);
      const list = khwaengIndex.get(key);
      if (list) list.push(entry);
      else khwaengIndex.set(key, [entry]);
    }
  }
}

/** สถานีรถไฟฟ้า: แปลง prefix ในข้อมูลเป็นชนิดพื้นที่ */
function transitType(station: string): LocalAreaType {
  if (station.startsWith('MRT ')) return 'mrt';
  if (station.startsWith('ARL ')) return 'arl';
  return 'bts';
}

function buildSuggestions(entry: IndexedDistrict): AreaSuggestion[] {
  const out: AreaSuggestion[] = [];

  for (const khwaeng of entry.record.khwaeng) {
    out.push({ name: khwaeng, type: 'subdistrict', relation: 'subdistrict', parent: entry.name });
  }

  for (const adjacent of entry.record.adjacent) {
    // เขตข้างเคียงอาจอยู่คนละจังหวัด — ใช้จังหวัดของเขตนั้นจริง ๆ ถ้ารู้จัก
    const known = districtIndex.get(normalizeAreaName(adjacent));
    out.push({
      name: adjacent,
      type: 'district',
      relation: 'adjacent',
      parent: known?.province ?? entry.province,
    });
  }

  for (const station of entry.record.transit ?? []) {
    out.push({ name: station, type: transitType(station), relation: 'transit', parent: entry.name });
  }

  return out;
}

/**
 * หาพื้นที่ใกล้เคียงของทำเลหลัก
 *
 * รับได้ทั้งชื่อเขต ("บางแค", "เขตบางแค") และชื่อแขวง ("บางหว้า" → เขตภาษีเจริญ)
 * คืน null เมื่อไม่รู้จักพื้นที่นั้น — ผู้เรียกต้องให้ผู้ใช้กรอกเองแทน ห้ามเดา
 */
export function findNearbyAreas(rawName: string): AreaMatch | null {
  const key = normalizeAreaName(rawName || '');
  if (!key) return null;

  const district = districtIndex.get(key);
  if (district) {
    return {
      name: district.name,
      type: 'district',
      province: district.province,
      matchedVia: 'district',
      // เขตหลายเขตมีแขวงชื่อเดียวกับเขต (เช่น เขตบางแค → แขวงบางแค)
      // ไม่ต้องเสนอ เพราะซ้ำกับทำเลหลักที่ผู้ใช้กรอกไปแล้ว
      suggestions: buildSuggestions(district).filter(s => normalizeAreaName(s.name) !== key),
    };
  }

  const parents = khwaengIndex.get(key);
  if (parents && parents.length > 0) {
    // แขวงชื่อซ้ำข้ามเขตได้ (เช่น "บางจาก" มีทั้งพระโขนงและภาษีเจริญ)
    // เลือกเขตแรกที่เจอ แต่แนบเขตอื่นที่ชื่อชนกันเป็นตัวเลือกด้วย
    const [first, ...others] = parents;
    const suggestions = buildSuggestions(first).filter(s => normalizeAreaName(s.name) !== key);
    for (const other of others) {
      suggestions.push({ name: other.name, type: 'district', relation: 'adjacent', parent: other.province });
    }
    return {
      name: first.name,
      type: 'district',
      province: first.province,
      matchedVia: 'subdistrict',
      suggestions,
    };
  }

  return null;
}

