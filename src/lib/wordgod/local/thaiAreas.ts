import type { LocalAreaType } from './types';

export interface AreaSuggestion {
  name: string;
  type: LocalAreaType;
  /** ความสัมพันธ์กับทำเลหลัก ใช้จัดกลุ่มตอนแสดงผล */
  relation: 'subdistrict' | 'adjacent' | 'transit' | 'sibling';
  /** เขต/อำเภอ/จังหวัดแม่ของชื่อนี้ */
  parent: string;
}

export interface AreaMatch {
  /** ชื่อเขต/อำเภอที่จับคู่ได้ */
  name: string;
  type: LocalAreaType;
  /** จังหวัดของพื้นที่นี้ */
  province: string;
  /** จับคู่จากชื่อเขตตรง ๆ หรือย้อนขึ้นมาจากชื่อแขวง */
  matchedVia: 'district' | 'subdistrict';
  suggestions: AreaSuggestion[];
}

interface DistrictRecord {
  /** แขวง / ตำบล ในเขตนี้ */
  khwaeng: string[];
  /** เขต/อำเภอที่มีอาณาเขตติดกัน (ชื่อล้วน — ข้ามจังหวัดได้) */
  adjacent: string[];
  /** สถานีรถไฟฟ้าในเขตนี้ (prefix บอกระบบ) */
  transit?: string[];
}

